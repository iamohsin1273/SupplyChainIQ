-- 1. Monthly revenue
SELECT * FROM SUPPLYCHAIN_DB.ANALYTICS.MONTHLY_REVENUE ORDER BY MONTH;
-- 2. Top-selling products (units)
SELECT PRODUCT_ID,SUM(QUANTITY) UNITS_SOLD,SUM(REVENUE) REVENUE FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS GROUP BY PRODUCT_ID ORDER BY UNITS_SOLD DESC LIMIT 10;
-- 3. Warehouse inventory availability
SELECT WAREHOUSE_ID,SUM(QUANTITY_ON_HAND) UNITS_AVAILABLE,SUM(INVENTORY_VALUE) INVENTORY_VALUE FROM SUPPLYCHAIN_DB.CORE.FACT_INVENTORY_SNAPSHOT GROUP BY WAREHOUSE_ID ORDER BY UNITS_AVAILABLE DESC;
-- 4. Products at risk of stockouts
SELECT * FROM SUPPLYCHAIN_DB.ANALYTICS.INVENTORY_RISK WHERE STOCK_RISK ORDER BY QUANTITY_ON_HAND;
-- 5. On-time delivery percentage
SELECT 100.0*COUNT_IF(ON_TIME)/NULLIF(COUNT_IF(ON_TIME IS NOT NULL),0) ON_TIME_DELIVERY_PCT FROM SUPPLYCHAIN_DB.CORE.FACT_SHIPMENTS;
-- 6. Average supplier lead time
SELECT SUPPLIER_ID,AVG(LEAD_TIME_DAYS) AVG_LEAD_TIME_DAYS FROM SUPPLYCHAIN_DB.CORE.FACT_PURCHASE_ORDERS WHERE LEAD_TIME_DAYS IS NOT NULL GROUP BY SUPPLIER_ID ORDER BY AVG_LEAD_TIME_DAYS DESC;
-- 7. Late shipments by warehouse
SELECT WAREHOUSE_ID,COUNT_IF(ON_TIME=FALSE) LATE_SHIPMENTS,COUNT(*) TOTAL_SHIPMENTS FROM SUPPLYCHAIN_DB.CORE.FACT_SHIPMENTS GROUP BY WAREHOUSE_ID ORDER BY LATE_SHIPMENTS DESC;
-- 8. Order fulfillment duration (order date to actual delivery)
SELECT F.ORDER_ID,DATEDIFF('DAY',F.ORDER_DATE,S.ACTUAL_DELIVERY_DATE) FULFILLMENT_DAYS FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS F JOIN SUPPLYCHAIN_DB.CORE.FACT_SHIPMENTS S USING(ORDER_ID) QUALIFY ROW_NUMBER() OVER(PARTITION BY F.ORDER_ID ORDER BY S.ACTUAL_DELIVERY_DATE)=1;
-- 9. Supplier performance ranking (lead-time proxy)
SELECT SUPPLIER_ID,AVG(LEAD_TIME_DAYS) AVG_LEAD_TIME_DAYS,DENSE_RANK() OVER(ORDER BY AVG(LEAD_TIME_DAYS)) PERFORMANCE_RANK FROM SUPPLYCHAIN_DB.CORE.FACT_PURCHASE_ORDERS GROUP BY SUPPLIER_ID;
-- 10. Month-over-month order growth
WITH M AS (SELECT DATE_TRUNC('MONTH',ORDER_DATE)::DATE MONTH,COUNT(DISTINCT ORDER_ID) ORDERS FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS GROUP BY 1)
SELECT MONTH,ORDERS,LAG(ORDERS) OVER(ORDER BY MONTH) PREVIOUS_MONTH,
 100.0*(ORDERS-LAG(ORDERS) OVER(ORDER BY MONTH))/NULLIF(LAG(ORDERS) OVER(ORDER BY MONTH),0) MOM_GROWTH_PCT FROM M ORDER BY MONTH;
-- 11. Revenue by product category
SELECT P.CATEGORY,SUM(F.REVENUE) REVENUE FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS F JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT P ON F.PRODUCT_ID=P.PRODUCT_ID AND P.IS_CURRENT GROUP BY P.CATEGORY ORDER BY REVENUE DESC;
-- 12. Data quality trend
SELECT TO_DATE(STARTED_AT) RUN_DATE,AVG(QUALITY_SCORE_PCT) AVG_QUALITY_SCORE,COUNT_IF(STATUS='FAILED') FAILED_RUNS FROM SUPPLYCHAIN_DB.MONITORING.PIPELINE_RUNS GROUP BY 1 ORDER BY 1;
