CREATE TABLE IF NOT EXISTS SUPPLYCHAIN_DB.MONITORING.PIPELINE_RUNS (
 BATCH_ID VARCHAR, STARTED_AT TIMESTAMP_NTZ, FINISHED_AT TIMESTAMP_NTZ, STATUS VARCHAR,
 SOURCE_ROWS NUMBER, ACCEPTED_ROWS NUMBER, REJECTED_ROWS NUMBER, QUALITY_SCORE_PCT NUMBER(5,2), ERROR_MESSAGE VARCHAR
);
CREATE TABLE IF NOT EXISTS SUPPLYCHAIN_DB.MONITORING.DATA_QUALITY_RESULTS (
 BATCH_ID VARCHAR, CHECK_NAME VARCHAR, SOURCE_TABLE VARCHAR, CHECKED_AT TIMESTAMP_NTZ DEFAULT CURRENT_TIMESTAMP(),
 CHECKED_ROWS NUMBER, FAILED_ROWS NUMBER, STATUS VARCHAR, DETAILS VARCHAR
);
