WHEN MATCHED THEN UPDATE SET
    PRODUCT_ID = S.PRODUCT_ID,
    WAREHOUSE_ID = S.WAREHOUSE_ID,
    SNAPSHOT_DATE = S.SNAPSHOT_DATE,
    QUANTITY_ON_HAND = S.QUANTITY_ON_HAND,
    UNIT_COST = S.UNIT_COST,
    INVENTORY_VALUE = S.INVENTORY_VALUE,
    BATCH_ID = S.BATCH_ID,
    LOADED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHEN NOT MATCHED THEN INSERT (
    INVENTORY_ID, PRODUCT_ID, WAREHOUSE_ID, SNAPSHOT_DATE, QUANTITY_ON_HAND,
    UNIT_COST, INVENTORY_VALUE, BATCH_ID, LOADED_AT
)
VALUES (
    S.INVENTORY_ID, S.PRODUCT_ID, S.WAREHOUSE_ID, S.SNAPSHOT_DATE, S.QUANTITY_ON_HAND,
    S.UNIT_COST, S.INVENTORY_VALUE, S.BATCH_ID, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
);

MERGE INTO SUPPLYCHAIN_DB.CORE.FACT_SHIPMENTS T
USING (
    SELECT S.SHIPMENT_ID, S.ORDER_ID, S.WAREHOUSE_ID, S.SHIP_DATE,
           S.PROMISED_DELIVERY_DATE, S.ACTUAL_DELIVERY_DATE,
           IFF(S.ACTUAL_DELIVERY_DATE IS NULL, NULL, S.ACTUAL_DELIVERY_DATE <= S.PROMISED_DELIVERY_DATE) AS ON_TIME,
           DATEDIFF('DAY', S.SHIP_DATE, S.ACTUAL_DELIVERY_DATE) AS TRANSIT_DAYS,
           S.BATCH_ID
    FROM SUPPLYCHAIN_DB.STAGING.SHIPMENTS_CLEAN S
    JOIN SUPPLYCHAIN_DB.CORE.DIM_WAREHOUSE W ON W.WAREHOUSE_ID = S.WAREHOUSE_ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY S.SHIPMENT_ID ORDER BY S.INGESTED_AT DESC NULLS LAST) = 1
) S
ON T.SHIPMENT_ID = S.SHIPMENT_ID
WHEN MATCHED THEN UPDATE SET
    ORDER_ID = S.ORDER_ID,
    WAREHOUSE_ID = S.WAREHOUSE_ID,
    SHIP_DATE = S.SHIP_DATE,
    PROMISED_DELIVERY_DATE = S.PROMISED_DELIVERY_DATE,
    ACTUAL_DELIVERY_DATE = S.ACTUAL_DELIVERY_DATE,
    ON_TIME = S.ON_TIME,
    TRANSIT_DAYS = S.TRANSIT_DAYS,
    BATCH_ID = S.BATCH_ID,
    LOADED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHEN NOT MATCHED THEN INSERT (
    SHIPMENT_ID, ORDER_ID, WAREHOUSE_ID, SHIP_DATE, PROMISED_DELIVERY_DATE,
    ACTUAL_DELIVERY_DATE, ON_TIME, TRANSIT_DAYS, BATCH_ID, LOADED_AT
)
VALUES (
    S.SHIPMENT_ID, S.ORDER_ID, S.WAREHOUSE_ID, S.SHIP_DATE, S.PROMISED_DELIVERY_DATE,
    S.ACTUAL_DELIVERY_DATE, S.ON_TIME, S.TRANSIT_DAYS, S.BATCH_ID, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
);

