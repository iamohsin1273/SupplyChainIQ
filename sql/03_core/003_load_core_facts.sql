MERGE INTO SUPPLYCHAIN_DB.CORE.FACT_ORDERS T
USING (
    SELECT I.ORDER_ITEM_ID, O.ORDER_ID, O.CUSTOMER_ID, I.PRODUCT_ID, D.PRODUCT_SK,
           O.ORDER_DATE, O.STATUS, I.QUANTITY, I.UNIT_PRICE,
           I.QUANTITY * I.UNIT_PRICE AS REVENUE, COALESCE(I.BATCH_ID, O.BATCH_ID) AS BATCH_ID
    FROM SUPPLYCHAIN_DB.STAGING.ORDER_ITEMS_CLEAN I
    JOIN SUPPLYCHAIN_DB.STAGING.ORDERS_CLEAN O ON O.ORDER_ID = I.ORDER_ID
    JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT D ON D.PRODUCT_ID = I.PRODUCT_ID AND D.IS_CURRENT
    JOIN SUPPLYCHAIN_DB.CORE.DIM_CUSTOMER C ON C.CUSTOMER_ID = O.CUSTOMER_ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY I.ORDER_ITEM_ID ORDER BY I.INGESTED_AT DESC NULLS LAST) = 1
) S
ON T.ORDER_ITEM_ID = S.ORDER_ITEM_ID
WHEN MATCHED THEN UPDATE SET
    ORDER_ID = S.ORDER_ID,
    CUSTOMER_ID = S.CUSTOMER_ID,
    PRODUCT_ID = S.PRODUCT_ID,
    PRODUCT_SK = COALESCE(T.PRODUCT_SK, S.PRODUCT_SK),
    ORDER_DATE = S.ORDER_DATE,
    STATUS = S.STATUS,
    QUANTITY = S.QUANTITY,
    UNIT_PRICE = S.UNIT_PRICE,
    REVENUE = S.REVENUE,
    BATCH_ID = S.BATCH_ID,
    LOADED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHEN NOT MATCHED THEN INSERT (
    ORDER_ITEM_ID, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, PRODUCT_SK, ORDER_DATE, STATUS,
    QUANTITY, UNIT_PRICE, REVENUE, BATCH_ID, LOADED_AT
)
VALUES (
    S.ORDER_ITEM_ID, S.ORDER_ID, S.CUSTOMER_ID, S.PRODUCT_ID, S.PRODUCT_SK, S.ORDER_DATE,
    S.STATUS, S.QUANTITY, S.UNIT_PRICE, S.REVENUE, S.BATCH_ID, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
);

MERGE INTO SUPPLYCHAIN_DB.CORE.FACT_INVENTORY_SNAPSHOT T
USING (
    SELECT I.INVENTORY_ID, I.PRODUCT_ID, I.WAREHOUSE_ID, I.SNAPSHOT_DATE,
           I.QUANTITY_ON_HAND, I.UNIT_COST, I.QUANTITY_ON_HAND * I.UNIT_COST AS INVENTORY_VALUE,
           I.BATCH_ID
    FROM SUPPLYCHAIN_DB.STAGING.INVENTORY_CLEAN I
    JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT P ON P.PRODUCT_ID = I.PRODUCT_ID AND P.IS_CURRENT
    JOIN SUPPLYCHAIN_DB.CORE.DIM_WAREHOUSE W ON W.WAREHOUSE_ID = I.WAREHOUSE_ID
    QUALIFY ROW_NUMBER() OVER (PARTITION BY I.INVENTORY_ID ORDER BY I.INGESTED_AT DESC NULLS LAST) = 1
) S
