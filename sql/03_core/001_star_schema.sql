CREATE TABLE IF NOT EXISTS SUPPLYCHAIN_DB.CORE.DIM_PRODUCT (
    PRODUCT_SK NUMBER AUTOINCREMENT START 1 INCREMENT 1,
    PRODUCT_ID VARCHAR NOT NULL,
    PRODUCT_NAME VARCHAR,
    CATEGORY VARCHAR,
    UNIT_PRICE NUMBER(12, 2),
    SUPPLIER_ID VARCHAR,
    EFFECTIVE_START TIMESTAMP_NTZ,
    EFFECTIVE_END TIMESTAMP_NTZ,
    IS_CURRENT BOOLEAN,
    ATTRIBUTE_HASH VARCHAR
);

