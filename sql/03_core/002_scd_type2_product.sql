-- Expire current product versions whose tracked attributes changed.
UPDATE SUPPLYCHAIN_DB.CORE.DIM_PRODUCT T
SET EFFECTIVE_END = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ,
    IS_CURRENT = FALSE
FROM SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN S
WHERE T.PRODUCT_ID = S.PRODUCT_ID
  AND T.IS_CURRENT = TRUE
  AND T.ATTRIBUTE_HASH <> SHA2(
      CONCAT_WS(
          '|',
          COALESCE(S.PRODUCT_NAME, ''),
          COALESCE(S.CATEGORY, ''),
          COALESCE(TO_VARCHAR(S.UNIT_PRICE), ''),
          COALESCE(S.SUPPLIER_ID, '')
      ),
      256
  );

-- Insert first versions and replacements after changed current versions were expired.
INSERT INTO SUPPLYCHAIN_DB.CORE.DIM_PRODUCT (
    PRODUCT_ID, PRODUCT_NAME, CATEGORY, UNIT_PRICE, SUPPLIER_ID,
    EFFECTIVE_START, EFFECTIVE_END, IS_CURRENT, ATTRIBUTE_HASH
)
SELECT S.PRODUCT_ID, S.PRODUCT_NAME, S.CATEGORY, S.UNIT_PRICE, S.SUPPLIER_ID,
       CURRENT_TIMESTAMP()::TIMESTAMP_NTZ, '9999-12-31'::TIMESTAMP_NTZ, TRUE,
       SHA2(
           CONCAT_WS(
               '|',
               COALESCE(S.PRODUCT_NAME, ''),
               COALESCE(S.CATEGORY, ''),
               COALESCE(TO_VARCHAR(S.UNIT_PRICE), ''),
               COALESCE(S.SUPPLIER_ID, '')
           ),
           256
       )
FROM SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN S
WHERE NOT EXISTS (
    SELECT 1
    FROM SUPPLYCHAIN_DB.CORE.DIM_PRODUCT T
    WHERE T.PRODUCT_ID = S.PRODUCT_ID
      AND T.IS_CURRENT = TRUE
);
