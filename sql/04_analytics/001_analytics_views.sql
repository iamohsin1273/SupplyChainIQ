CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.FACT_ORDERS AS
SELECT F.ORDER_ITEM_ID, F.ORDER_ID, F.CUSTOMER_ID, F.PRODUCT_ID, F.ORDER_DATE, F.STATUS,
       F.QUANTITY, F.UNIT_PRICE, F.REVENUE, F.BATCH_ID,
       P.PRODUCT_NAME, P.CATEGORY
FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS F
LEFT JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT P ON P.PRODUCT_SK = F.PRODUCT_SK;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.MONTHLY_REVENUE AS
SELECT DATE_TRUNC('MONTH', ORDER_DATE)::DATE AS MONTH,
       COUNT(DISTINCT ORDER_ID) AS ORDERS,
       SUM(REVENUE) AS REVENUE,
       SUM(QUANTITY) AS UNITS
FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS
GROUP BY 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.TOP_PRODUCTS AS
SELECT F.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY,
       SUM(F.QUANTITY) AS UNITS_SOLD, SUM(F.REVENUE) AS REVENUE
FROM SUPPLYCHAIN_DB.CORE.FACT_ORDERS F
JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT P ON P.PRODUCT_SK = F.PRODUCT_SK
GROUP BY F.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.INVENTORY_ANALYTICS AS
SELECT I.INVENTORY_ID, I.PRODUCT_ID, P.PRODUCT_NAME, P.CATEGORY,
       I.WAREHOUSE_ID, W.WAREHOUSE_NAME, I.SNAPSHOT_DATE, I.QUANTITY_ON_HAND,
       P.REORDER_LEVEL,
       I.QUANTITY_ON_HAND < P.REORDER_LEVEL AS STOCK_RISK,
       I.UNIT_COST, I.INVENTORY_VALUE
FROM SUPPLYCHAIN_DB.CORE.FACT_INVENTORY_SNAPSHOT I
JOIN SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN P ON P.PRODUCT_ID = I.PRODUCT_ID
JOIN SUPPLYCHAIN_DB.CORE.DIM_WAREHOUSE W ON W.WAREHOUSE_ID = I.WAREHOUSE_ID;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.SHIPMENT_ANALYTICS AS
SELECT S.SHIPMENT_ID, S.ORDER_ID, S.WAREHOUSE_ID, S.SHIP_DATE,
       S.PROMISED_DELIVERY_DATE, S.ACTUAL_DELIVERY_DATE, S.ON_TIME, S.TRANSIT_DAYS
FROM SUPPLYCHAIN_DB.CORE.FACT_SHIPMENTS S;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.DIM_SUPPLIER AS
SELECT SUPPLIER_ID, SUPPLIER_NAME, COUNTRY, LEAD_TIME_DAYS
FROM SUPPLYCHAIN_DB.CORE.DIM_SUPPLIER;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.ANALYTICS.REJECTED_RECORDS AS
SELECT 'orders' AS SOURCE_TABLE, ORDER_ID AS BUSINESS_KEY, SOURCE_FILE, BATCH_ID,
       'order_id is required' AS REJECTION_REASON
FROM SUPPLYCHAIN_DB.RAW.ORDERS
WHERE NULLIF(TRIM(ORDER_ID), '') IS NULL
UNION ALL
SELECT 'orders', ORDER_ID, SOURCE_FILE, BATCH_ID, 'invalid order_date'
FROM SUPPLYCHAIN_DB.RAW.ORDERS
WHERE TRY_TO_DATE(ORDER_DATE) IS NULL
UNION ALL
SELECT 'orders', ORDER_ID, SOURCE_FILE, BATCH_ID, 'customer_id references unknown customers'
FROM SUPPLYCHAIN_DB.RAW.ORDERS O
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.CUSTOMERS C WHERE C.CUSTOMER_ID = O.CUSTOMER_ID
)
UNION ALL
SELECT 'order_items', ORDER_ITEM_ID, SOURCE_FILE, BATCH_ID, 'quantity must be positive'
FROM SUPPLYCHAIN_DB.RAW.ORDER_ITEMS
WHERE TRY_TO_NUMBER(QUANTITY) IS NULL OR TRY_TO_NUMBER(QUANTITY) <= 0
UNION ALL
SELECT 'order_items', ORDER_ITEM_ID, SOURCE_FILE, BATCH_ID, 'unit_price must be non-negative'
FROM SUPPLYCHAIN_DB.RAW.ORDER_ITEMS
WHERE TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) IS NULL OR TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) < 0
UNION ALL
SELECT 'order_items', ORDER_ITEM_ID, SOURCE_FILE, BATCH_ID, 'order_id references unknown orders'
FROM SUPPLYCHAIN_DB.RAW.ORDER_ITEMS I
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.ORDERS O WHERE O.ORDER_ID = I.ORDER_ID
)
UNION ALL
SELECT 'order_items', ORDER_ITEM_ID, SOURCE_FILE, BATCH_ID, 'product_id references unknown products'
FROM SUPPLYCHAIN_DB.RAW.ORDER_ITEMS I
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.PRODUCTS P WHERE P.PRODUCT_ID = I.PRODUCT_ID
)
UNION ALL
SELECT 'products', PRODUCT_ID, SOURCE_FILE, BATCH_ID, 'unit_price must be positive'
FROM SUPPLYCHAIN_DB.RAW.PRODUCTS
WHERE TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) IS NULL OR TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) <= 0
UNION ALL
SELECT 'products', PRODUCT_ID, SOURCE_FILE, BATCH_ID, 'supplier_id references unknown suppliers'
FROM SUPPLYCHAIN_DB.RAW.PRODUCTS P
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.SUPPLIERS S WHERE S.SUPPLIER_ID = P.SUPPLIER_ID
)
UNION ALL
SELECT 'customers', CUSTOMER_ID, SOURCE_FILE, BATCH_ID, 'customer_id is required'
FROM SUPPLYCHAIN_DB.RAW.CUSTOMERS
WHERE NULLIF(TRIM(CUSTOMER_ID), '') IS NULL
UNION ALL
SELECT 'warehouses', WAREHOUSE_ID, SOURCE_FILE, BATCH_ID, 'warehouse_id is required'
FROM SUPPLYCHAIN_DB.RAW.WAREHOUSES
WHERE NULLIF(TRIM(WAREHOUSE_ID), '') IS NULL
UNION ALL
SELECT 'inventory', INVENTORY_ID, SOURCE_FILE, BATCH_ID, 'quantity_on_hand must be non-negative'
FROM SUPPLYCHAIN_DB.RAW.INVENTORY
WHERE TRY_TO_NUMBER(QUANTITY_ON_HAND) IS NULL OR TRY_TO_NUMBER(QUANTITY_ON_HAND) < 0
UNION ALL
SELECT 'inventory', INVENTORY_ID, SOURCE_FILE, BATCH_ID, 'invalid snapshot_date'
FROM SUPPLYCHAIN_DB.RAW.INVENTORY
WHERE TRY_TO_DATE(SNAPSHOT_DATE) IS NULL
UNION ALL
SELECT 'inventory', INVENTORY_ID, SOURCE_FILE, BATCH_ID, 'product_id references unknown products'
FROM SUPPLYCHAIN_DB.RAW.INVENTORY I
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.PRODUCTS P WHERE P.PRODUCT_ID = I.PRODUCT_ID
)
UNION ALL
SELECT 'inventory', INVENTORY_ID, SOURCE_FILE, BATCH_ID, 'warehouse_id references unknown warehouses'
FROM SUPPLYCHAIN_DB.RAW.INVENTORY I
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.WAREHOUSES W WHERE W.WAREHOUSE_ID = I.WAREHOUSE_ID
)
UNION ALL
SELECT 'suppliers', SUPPLIER_ID, SOURCE_FILE, BATCH_ID, 'supplier_id is required'
FROM SUPPLYCHAIN_DB.RAW.SUPPLIERS
WHERE NULLIF(TRIM(SUPPLIER_ID), '') IS NULL
UNION ALL
SELECT 'purchase_orders', PURCHASE_ORDER_ID, SOURCE_FILE, BATCH_ID, 'quantity must be positive'
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS
WHERE TRY_TO_NUMBER(QUANTITY) IS NULL OR TRY_TO_NUMBER(QUANTITY) <= 0
UNION ALL
SELECT 'purchase_orders', PURCHASE_ORDER_ID, SOURCE_FILE, BATCH_ID, 'invalid order_date'
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS
WHERE TRY_TO_DATE(ORDER_DATE) IS NULL
UNION ALL
SELECT 'purchase_orders', PURCHASE_ORDER_ID, SOURCE_FILE, BATCH_ID, 'received_date precedes order_date'
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS
WHERE TRY_TO_DATE(RECEIVED_DATE) < TRY_TO_DATE(ORDER_DATE)
UNION ALL
SELECT 'purchase_orders', PURCHASE_ORDER_ID, SOURCE_FILE, BATCH_ID, 'supplier_id references unknown suppliers'
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS P
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.SUPPLIERS S WHERE S.SUPPLIER_ID = P.SUPPLIER_ID
)
UNION ALL
SELECT 'purchase_orders', PURCHASE_ORDER_ID, SOURCE_FILE, BATCH_ID, 'product_id references unknown products'
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS P
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.PRODUCTS D WHERE D.PRODUCT_ID = P.PRODUCT_ID
)
UNION ALL
SELECT 'shipments', SHIPMENT_ID, SOURCE_FILE, BATCH_ID, 'invalid ship_date or promised_delivery_date'
FROM SUPPLYCHAIN_DB.RAW.SHIPMENTS
WHERE TRY_TO_DATE(SHIP_DATE) IS NULL
   OR TRY_TO_DATE(PROMISED_DELIVERY_DATE) IS NULL
   OR TRY_TO_DATE(PROMISED_DELIVERY_DATE) < TRY_TO_DATE(SHIP_DATE)
UNION ALL
SELECT 'shipments', SHIPMENT_ID, SOURCE_FILE, BATCH_ID, 'invalid actual_delivery_date'
FROM SUPPLYCHAIN_DB.RAW.SHIPMENTS
WHERE NULLIF(TRIM(ACTUAL_DELIVERY_DATE), '') IS NOT NULL
  AND (
      TRY_TO_DATE(ACTUAL_DELIVERY_DATE) IS NULL
      OR TRY_TO_DATE(ACTUAL_DELIVERY_DATE) < TRY_TO_DATE(SHIP_DATE)
  )
UNION ALL
SELECT 'shipments', SHIPMENT_ID, SOURCE_FILE, BATCH_ID, 'order_id references unknown orders'
FROM SUPPLYCHAIN_DB.RAW.SHIPMENTS S
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.ORDERS O WHERE O.ORDER_ID = S.ORDER_ID
)
UNION ALL
SELECT 'shipments', SHIPMENT_ID, SOURCE_FILE, BATCH_ID, 'warehouse_id references unknown warehouses'
FROM SUPPLYCHAIN_DB.RAW.SHIPMENTS S
WHERE NOT EXISTS (
    SELECT 1 FROM SUPPLYCHAIN_DB.RAW.WAREHOUSES W WHERE W.WAREHOUSE_ID = S.WAREHOUSE_ID
);
