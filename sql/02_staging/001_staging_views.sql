CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.CUSTOMERS_CLEAN AS
SELECT CUSTOMER_ID, TRIM(REGION) AS REGION, TRIM(CUSTOMER_SEGMENT) AS CUSTOMER_SEGMENT,
       BATCH_ID, INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.CUSTOMERS
WHERE NULLIF(TRIM(CUSTOMER_ID), '') IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY CUSTOMER_ID ORDER BY INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.SUPPLIERS_CLEAN AS
SELECT SUPPLIER_ID, TRIM(SUPPLIER_NAME) AS SUPPLIER_NAME, TRIM(COUNTRY) AS COUNTRY,
       TRY_TO_NUMBER(LEAD_TIME_DAYS) AS LEAD_TIME_DAYS, BATCH_ID, INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.SUPPLIERS
WHERE NULLIF(TRIM(SUPPLIER_ID), '') IS NOT NULL
  AND TRY_TO_NUMBER(LEAD_TIME_DAYS) >= 0
QUALIFY ROW_NUMBER() OVER (PARTITION BY SUPPLIER_ID ORDER BY INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.WAREHOUSES_CLEAN AS
SELECT WAREHOUSE_ID, TRIM(WAREHOUSE_NAME) AS WAREHOUSE_NAME, TRIM(REGION) AS REGION,
       BATCH_ID, INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.WAREHOUSES
WHERE NULLIF(TRIM(WAREHOUSE_ID), '') IS NOT NULL
QUALIFY ROW_NUMBER() OVER (PARTITION BY WAREHOUSE_ID ORDER BY INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN AS
SELECT PRODUCT_ID, TRIM(PRODUCT_NAME) AS PRODUCT_NAME, TRIM(CATEGORY) AS CATEGORY,
       TRY_TO_DECIMAL(UNIT_PRICE, 12, 2) AS UNIT_PRICE, SUPPLIER_ID,
       TRY_TO_NUMBER(REORDER_LEVEL) AS REORDER_LEVEL, BATCH_ID, INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.PRODUCTS P
WHERE NULLIF(TRIM(P.PRODUCT_ID), '') IS NOT NULL
  AND TRY_TO_DECIMAL(P.UNIT_PRICE, 12, 2) > 0
  AND TRY_TO_NUMBER(P.REORDER_LEVEL) >= 0
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.SUPPLIERS_CLEAN S
      WHERE S.SUPPLIER_ID = P.SUPPLIER_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY P.PRODUCT_ID ORDER BY P.INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.ORDERS_CLEAN AS
SELECT O.ORDER_ID, O.CUSTOMER_ID, TRY_TO_DATE(O.ORDER_DATE) AS ORDER_DATE,
       LOWER(TRIM(O.STATUS)) AS STATUS, O.BATCH_ID, O.INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.ORDERS O
WHERE NULLIF(TRIM(O.ORDER_ID), '') IS NOT NULL
  AND TRY_TO_DATE(O.ORDER_DATE) IS NOT NULL
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.CUSTOMERS_CLEAN C
      WHERE C.CUSTOMER_ID = O.CUSTOMER_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY O.ORDER_ID ORDER BY O.INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.ORDER_ITEMS_CLEAN AS
SELECT I.ORDER_ITEM_ID, I.ORDER_ID, I.PRODUCT_ID, TRY_TO_NUMBER(I.QUANTITY) AS QUANTITY,
       TRY_TO_DECIMAL(I.UNIT_PRICE, 12, 2) AS UNIT_PRICE, I.BATCH_ID, I.INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.ORDER_ITEMS I
WHERE NULLIF(TRIM(I.ORDER_ITEM_ID), '') IS NOT NULL
  AND TRY_TO_NUMBER(I.QUANTITY) > 0
  AND TRY_TO_DECIMAL(I.UNIT_PRICE, 12, 2) >= 0
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.ORDERS_CLEAN O WHERE O.ORDER_ID = I.ORDER_ID
  )
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN P WHERE P.PRODUCT_ID = I.PRODUCT_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY I.ORDER_ITEM_ID ORDER BY I.INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.INVENTORY_CLEAN AS
SELECT I.INVENTORY_ID, I.PRODUCT_ID, I.WAREHOUSE_ID, TRY_TO_DATE(I.SNAPSHOT_DATE) AS SNAPSHOT_DATE,
       TRY_TO_NUMBER(I.QUANTITY_ON_HAND) AS QUANTITY_ON_HAND,
       TRY_TO_DECIMAL(I.UNIT_COST, 12, 2) AS UNIT_COST, I.BATCH_ID, I.INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.INVENTORY I
WHERE NULLIF(TRIM(I.INVENTORY_ID), '') IS NOT NULL
  AND TRY_TO_DATE(I.SNAPSHOT_DATE) IS NOT NULL
  AND TRY_TO_NUMBER(I.QUANTITY_ON_HAND) >= 0
  AND TRY_TO_DECIMAL(I.UNIT_COST, 12, 2) >= 0
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN P WHERE P.PRODUCT_ID = I.PRODUCT_ID
  )
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.WAREHOUSES_CLEAN W WHERE W.WAREHOUSE_ID = I.WAREHOUSE_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY I.INVENTORY_ID ORDER BY I.INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.PURCHASE_ORDERS_CLEAN AS
SELECT P.PURCHASE_ORDER_ID, P.SUPPLIER_ID, P.PRODUCT_ID, TRY_TO_DATE(P.ORDER_DATE) AS ORDER_DATE,
       TRY_TO_NUMBER(P.QUANTITY) AS QUANTITY, TRY_TO_DATE(P.RECEIVED_DATE) AS RECEIVED_DATE,
       P.BATCH_ID, P.INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.PURCHASE_ORDERS P
WHERE NULLIF(TRIM(P.PURCHASE_ORDER_ID), '') IS NOT NULL
  AND TRY_TO_DATE(P.ORDER_DATE) IS NOT NULL
  AND TRY_TO_NUMBER(P.QUANTITY) > 0
  AND (NULLIF(TRIM(P.RECEIVED_DATE), '') IS NULL OR TRY_TO_DATE(P.RECEIVED_DATE) >= TRY_TO_DATE(P.ORDER_DATE))
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.SUPPLIERS_CLEAN S WHERE S.SUPPLIER_ID = P.SUPPLIER_ID
  )
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.PRODUCTS_CLEAN D WHERE D.PRODUCT_ID = P.PRODUCT_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY P.PURCHASE_ORDER_ID ORDER BY P.INGESTED_AT DESC NULLS LAST) = 1;

CREATE OR REPLACE VIEW SUPPLYCHAIN_DB.STAGING.SHIPMENTS_CLEAN AS
SELECT S.SHIPMENT_ID, S.ORDER_ID, S.WAREHOUSE_ID, TRY_TO_DATE(S.SHIP_DATE) AS SHIP_DATE,
       TRY_TO_DATE(S.PROMISED_DELIVERY_DATE) AS PROMISED_DELIVERY_DATE,
       TRY_TO_DATE(S.ACTUAL_DELIVERY_DATE) AS ACTUAL_DELIVERY_DATE, S.BATCH_ID, S.INGESTED_AT
FROM SUPPLYCHAIN_DB.RAW.SHIPMENTS S
WHERE NULLIF(TRIM(S.SHIPMENT_ID), '') IS NOT NULL
  AND TRY_TO_DATE(S.SHIP_DATE) IS NOT NULL
  AND TRY_TO_DATE(S.PROMISED_DELIVERY_DATE) >= TRY_TO_DATE(S.SHIP_DATE)
  AND (
      NULLIF(TRIM(S.ACTUAL_DELIVERY_DATE), '') IS NULL
      OR TRY_TO_DATE(S.ACTUAL_DELIVERY_DATE) >= TRY_TO_DATE(S.SHIP_DATE)
  )
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.ORDERS_CLEAN O WHERE O.ORDER_ID = S.ORDER_ID
  )
  AND EXISTS (
      SELECT 1 FROM SUPPLYCHAIN_DB.STAGING.WAREHOUSES_CLEAN W WHERE W.WAREHOUSE_ID = S.WAREHOUSE_ID
  )
QUALIFY ROW_NUMBER() OVER (PARTITION BY S.SHIPMENT_ID ORDER BY S.INGESTED_AT DESC NULLS LAST) = 1;
