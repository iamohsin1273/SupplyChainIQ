-- Optional incremental example. Run only after initial RAW/CORE loads and after
-- reviewing task/warehouse privileges. This task is not resumed automatically.
CREATE OR REPLACE STREAM SUPPLYCHAIN_DB.RAW.ORDERS_STREAM
    ON TABLE SUPPLYCHAIN_DB.RAW.ORDERS
    APPEND_ONLY = TRUE;

CREATE OR REPLACE TASK SUPPLYCHAIN_DB.CORE.PROCESS_NEW_ORDERS_TASK
    WAREHOUSE = SUPPLYCHAIN_WH
    SCHEDULE = '5 MINUTE'
    WHEN SYSTEM$STREAM_HAS_DATA('SUPPLYCHAIN_DB.RAW.ORDERS_STREAM')
AS
MERGE INTO SUPPLYCHAIN_DB.CORE.FACT_ORDERS T
USING (
    SELECT I.ORDER_ITEM_ID, O.ORDER_ID, O.CUSTOMER_ID, I.PRODUCT_ID, D.PRODUCT_SK,
           TRY_TO_DATE(O.ORDER_DATE) AS ORDER_DATE, LOWER(TRIM(O.STATUS)) AS STATUS,
           I.QUANTITY, I.UNIT_PRICE, I.QUANTITY * I.UNIT_PRICE AS REVENUE,
           O.BATCH_ID
    FROM SUPPLYCHAIN_DB.RAW.ORDERS_STREAM O
    JOIN SUPPLYCHAIN_DB.STAGING.ORDER_ITEMS_CLEAN I ON I.ORDER_ID = O.ORDER_ID
    JOIN SUPPLYCHAIN_DB.CORE.DIM_PRODUCT D ON D.PRODUCT_ID = I.PRODUCT_ID AND D.IS_CURRENT
    JOIN SUPPLYCHAIN_DB.CORE.DIM_CUSTOMER C ON C.CUSTOMER_ID = O.CUSTOMER_ID
    WHERE METADATA$ACTION = 'INSERT'
      AND METADATA$ISUPDATE = FALSE
      AND TRY_TO_DATE(O.ORDER_DATE) IS NOT NULL
    QUALIFY ROW_NUMBER() OVER (PARTITION BY I.ORDER_ITEM_ID ORDER BY O.INGESTED_AT DESC NULLS LAST) = 1
) S
ON T.ORDER_ITEM_ID = S.ORDER_ITEM_ID
WHEN MATCHED THEN UPDATE SET
    ORDER_ID = S.ORDER_ID,
    CUSTOMER_ID = S.CUSTOMER_ID,
    PRODUCT_ID = S.PRODUCT_ID,
    PRODUCT_SK = COALESCE(T.PRODUCT_SK, S.PRODUCT_SK),
    ORDER_DATE = S.ORDER_DATE,
    STATUS = S.STATUS,
    QUANTITY = S.QUANTITY,
    UNIT_PRICE = S.UNIT_PRICE,
    REVENUE = S.REVENUE,
    BATCH_ID = S.BATCH_ID,
    LOADED_AT = CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
WHEN NOT MATCHED THEN INSERT (
    ORDER_ITEM_ID, ORDER_ID, CUSTOMER_ID, PRODUCT_ID, PRODUCT_SK, ORDER_DATE, STATUS,
    QUANTITY, UNIT_PRICE, REVENUE, BATCH_ID, LOADED_AT
)
VALUES (
    S.ORDER_ITEM_ID, S.ORDER_ID, S.CUSTOMER_ID, S.PRODUCT_ID, S.PRODUCT_SK, S.ORDER_DATE,
    S.STATUS, S.QUANTITY, S.UNIT_PRICE, S.REVENUE, S.BATCH_ID, CURRENT_TIMESTAMP()::TIMESTAMP_NTZ
);

